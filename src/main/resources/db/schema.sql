SET client_encoding = 'UTF8'; -- nếu không, psql trên Windows sẽ đọc file UTF-8 này như WIN1252
-- Tìm kiếm bỏ qua dấu ("ao" tìm ra "áo") nhờ extension unaccent, có sẵn trong PostgreSQL.
CREATE EXTENSION IF NOT EXISTS unaccent;
-- Schema PostgreSQL 17: sáu bảng. Thời gian lưu theo giờ UTC (timestamp without time zone).
-- Email, tên danh mục và slug là duy nhất, không phân biệt hoa thường (unique index trên lower(cột)).

CREATE TABLE users (
 user_id BIGINT GENERATED BY DEFAULT AS IDENTITY, full_name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL,
 password_hash CHAR(64) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
 created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
 PRIMARY KEY(user_id),
 CONSTRAINT chk_users_role CHECK(role IN ('CUSTOMER','ADMIN'))
);
CREATE UNIQUE INDEX uq_users_email ON users(lower(email));

CREATE TABLE categories (
 category_id BIGINT GENERATED BY DEFAULT AS IDENTITY, name VARCHAR(100) NOT NULL, slug VARCHAR(120) NOT NULL,
 PRIMARY KEY(category_id)
);
CREATE UNIQUE INDEX uq_categories_name ON categories(lower(name));
CREATE UNIQUE INDEX uq_categories_slug ON categories(lower(slug));

CREATE TABLE products (
 product_id BIGINT GENERATED BY DEFAULT AS IDENTITY, category_id BIGINT NOT NULL, name VARCHAR(160) NOT NULL, description TEXT,
 color VARCHAR(40) NOT NULL, price NUMERIC(12,2) NOT NULL, image_url VARCHAR(1000),
 active BOOLEAN NOT NULL DEFAULT TRUE, featured BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
 PRIMARY KEY(product_id), CONSTRAINT chk_products_price CHECK(price>=0),
 CONSTRAINT fk_products_category FOREIGN KEY(category_id) REFERENCES categories(category_id) ON DELETE RESTRICT
);

-- Mỗi sản phẩm có đúng ba size S, M, L; xóa sản phẩm thì xóa luôn các size của nó.
CREATE TABLE product_sizes (
 size_id BIGINT GENERATED BY DEFAULT AS IDENTITY, product_id BIGINT NOT NULL, size VARCHAR(1) NOT NULL, stock INT NOT NULL DEFAULT 0,
 PRIMARY KEY(size_id),
 CONSTRAINT chk_sizes_size CHECK(size IN ('S','M','L')),
 CONSTRAINT chk_sizes_stock CHECK(stock>=0), -- tồn kho không bao giờ âm
 CONSTRAINT uq_sizes_product_size UNIQUE(product_id,size),
 CONSTRAINT fk_sizes_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE CASCADE
);

CREATE TABLE orders (
 order_id BIGINT GENERATED BY DEFAULT AS IDENTITY, customer_id BIGINT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 recipient_name VARCHAR(120) NOT NULL, recipient_phone VARCHAR(30) NOT NULL, shipping_address VARCHAR(500) NOT NULL,
 subtotal NUMERIC(12,2) NOT NULL, discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0, total NUMERIC(12,2) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
 PRIMARY KEY(order_id),
 CONSTRAINT chk_orders_status CHECK(status IN ('PENDING','CONFIRMED','SHIPPING','COMPLETED','CANCELLED')),
 CONSTRAINT chk_orders_amounts CHECK(subtotal>=0 AND discount_amount>=0 AND total=subtotal-discount_amount),
 CONSTRAINT fk_orders_customer FOREIGN KEY(customer_id) REFERENCES users(user_id) ON DELETE RESTRICT
);

-- Size đã có người đặt thì không xóa được nữa (RESTRICT), nên admin chỉ có thể tắt sản phẩm đi.
CREATE TABLE order_items (
 order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY, order_id BIGINT NOT NULL, size_id BIGINT NOT NULL,
 product_name VARCHAR(160) NOT NULL, size VARCHAR(1) NOT NULL, color VARCHAR(40) NOT NULL,
 quantity INT NOT NULL, unit_price NUMERIC(12,2) NOT NULL, line_total NUMERIC(12,2) NOT NULL,
 PRIMARY KEY(order_item_id),
 CONSTRAINT chk_order_items_quantity CHECK(quantity>0),
 CONSTRAINT fk_order_items_order FOREIGN KEY(order_id) REFERENCES orders(order_id) ON DELETE RESTRICT,
 CONSTRAINT fk_order_items_size FOREIGN KEY(size_id) REFERENCES product_sizes(size_id) ON DELETE RESTRICT
);
